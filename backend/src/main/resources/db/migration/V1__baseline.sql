-- Version 1: the tables as Hibernate created them before Flyway was added
-- (November 2026).
--
-- Existing databases already have these tables. Flyway marks them as
-- version 1 without running this file (spring.flyway.baseline-on-migrate).
-- New databases, including the in-memory test database, run it.
--
-- Constraint names are copied from the existing database, so that later
-- migrations can refer to the same names everywhere.

CREATE TABLE menu_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    available   boolean        NOT NULL,
    category    varchar(255)   NOT NULL,
    description varchar(1000),
    name        varchar(255)   NOT NULL,
    notes       varchar(1000),
    price       numeric(10, 2) NOT NULL,
    size_volume varchar(255),
    subcategory varchar(255),
    CONSTRAINT menu_items_pkey PRIMARY KEY (id)
);

CREATE TABLE customer_orders (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at      timestamp(6)   NOT NULL,
    order_reference uuid           NOT NULL,
    status          varchar(255)   NOT NULL,
    total_price     numeric(10, 2) NOT NULL,
    CONSTRAINT customer_orders_pkey PRIMARY KEY (id),
    CONSTRAINT uk8qtjyl24ya93r3vbsgbljff33 UNIQUE (order_reference),
    CONSTRAINT customer_orders_status_check
        CHECK (status IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE order_items (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    line_total   numeric(10, 2) NOT NULL,
    product_name varchar(255)   NOT NULL,
    quantity     integer        NOT NULL,
    unit_price   numeric(10, 2) NOT NULL,
    order_id     bigint         NOT NULL,
    menu_item_id bigint         NOT NULL,
    CONSTRAINT order_items_pkey PRIMARY KEY (id),
    CONSTRAINT fkb2vrrqy10nnyqhb5ergl5498r
        FOREIGN KEY (order_id) REFERENCES customer_orders (id),
    CONSTRAINT fkdtfg1f49yr5yye2fpl2xid2xo
        FOREIGN KEY (menu_item_id) REFERENCES menu_items (id)
);
