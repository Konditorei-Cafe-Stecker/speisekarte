-- Version 2: personal accounts for the café staff.
--
-- Accounts are never deleted, only deactivated, so that later records
-- (for example who confirmed an order) keep pointing at a real person.
-- Passwords are stored only as hashes (bcrypt by default).

CREATE TABLE staff_accounts (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    username             varchar(50)                 NOT NULL,
    display_name         varchar(100)                NOT NULL,
    password_hash        varchar(255)                NOT NULL,
    role                 varchar(20)                 NOT NULL,
    active               boolean                     NOT NULL,
    must_change_password boolean                     NOT NULL,
    created_at           timestamp(6) with time zone NOT NULL,
    password_changed_at  timestamp(6) with time zone NOT NULL,
    last_login_at        timestamp(6) with time zone,
    CONSTRAINT staff_accounts_pkey PRIMARY KEY (id),
    CONSTRAINT staff_accounts_username_key UNIQUE (username),
    CONSTRAINT staff_accounts_role_check CHECK (role IN ('STAFF', 'ADMIN'))
);
