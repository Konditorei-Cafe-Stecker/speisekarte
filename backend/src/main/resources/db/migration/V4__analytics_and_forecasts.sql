-- Version 4: what the analysis, forecasts and the owner's planning page need.
--
-- customer_orders.data_source
--   REAL for orders from the website, SYNTHETIC for the simulated history
--   (see docs/synthetic-data.md). Orders saved before this version are REAL.
--
-- weather_hourly, local_events
--   Real Bremen context: hourly DWD weather and Werder Bremen home matches /
--   city events. Filled from backend/src/main/resources/context/*.csv.
--
-- forecast_days, forecast_hours, forecast_products
--   Written by analysis/forecast_and_offers.py --publish, read by
--   GET /api/admin/forecast. Older days are kept to check forecasts later.

ALTER TABLE customer_orders
    ADD COLUMN data_source varchar(20) DEFAULT 'REAL' NOT NULL;
ALTER TABLE customer_orders
    ADD CONSTRAINT customer_orders_data_source_check
    CHECK (data_source IN ('REAL', 'SYNTHETIC'));
CREATE INDEX customer_orders_data_source_idx ON customer_orders (data_source);

CREATE TABLE weather_hourly (
    observed_at      timestamp(6) with time zone NOT NULL,
    temperature_c    numeric(4, 1)               NOT NULL,
    precipitation_mm numeric(5, 1)               NOT NULL,
    sunshine_min     integer,
    cloud_cover_pct  integer,
    wind_speed_kmh   numeric(5, 1),
    condition        varchar(20),
    station          varchar(10)                 NOT NULL,
    CONSTRAINT weather_hourly_pkey PRIMARY KEY (observed_at)
);

CREATE TABLE local_events (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    type               varchar(20)                 NOT NULL,
    name               varchar(255)                NOT NULL,
    starts_at          timestamp(6) with time zone NOT NULL,
    ends_at            timestamp(6) with time zone NOT NULL,
    location           varchar(255)                NOT NULL,
    approx_distance_km double precision,
    source             varchar(500)                NOT NULL,
    note               varchar(500),
    CONSTRAINT local_events_pkey PRIMARY KEY (id),
    CONSTRAINT local_events_type_check
        CHECK (type IN ('FOOTBALL', 'FAIR', 'CHRISTMAS_MARKET', 'FESTIVAL', 'PARADE'))
);
CREATE INDEX local_events_starts_at_idx ON local_events (starts_at);

CREATE TABLE forecast_days (
    forecast_day     date                        NOT NULL,
    expected_orders  double precision            NOT NULL,
    orders_low       integer                     NOT NULL,
    orders_high      integer                     NOT NULL,
    expected_revenue numeric(10, 2)              NOT NULL,
    revenue_low      numeric(10, 2)              NOT NULL,
    revenue_high     numeric(10, 2)              NOT NULL,
    temp_min         double precision,
    temp_max         double precision,
    rainy_hours      integer                     NOT NULL,
    events           varchar(1000),
    offers           varchar(1000),
    basis            varchar(20)                 NOT NULL,
    generated_at     timestamp(6) with time zone NOT NULL,
    CONSTRAINT forecast_days_pkey PRIMARY KEY (forecast_day)
);

CREATE TABLE forecast_hours (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    forecast_day    date             NOT NULL,
    local_hour      integer          NOT NULL,
    expected_orders double precision NOT NULL,
    orders_high     integer          NOT NULL,
    CONSTRAINT forecast_hours_pkey PRIMARY KEY (id)
);
CREATE INDEX forecast_hours_day_idx ON forecast_hours (forecast_day);

CREATE TABLE forecast_products (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    forecast_day   date             NOT NULL,
    menu_item_id   bigint           NOT NULL,
    product_label  varchar(255)     NOT NULL,
    category       varchar(255)     NOT NULL,
    subcategory    varchar(255),
    unit_price     numeric(10, 2)   NOT NULL,
    expected_units double precision NOT NULL,
    CONSTRAINT forecast_products_pkey PRIMARY KEY (id),
    CONSTRAINT forecast_products_menu_item_fkey
        FOREIGN KEY (menu_item_id) REFERENCES menu_items (id)
);
CREATE INDEX forecast_products_day_idx ON forecast_products (forecast_day);
